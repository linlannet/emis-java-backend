package net.linlan.emis.console.controller;

import java.util.List;
import java.util.stream.Collectors;

import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import net.linlan.commons.core.ResponseResult;
import net.linlan.emis.support.constant.EmisConstants;
import net.linlan.emis.support.utils.CountryUtils;

/**
 * 国家信息
 *
 * @author Linlan
 */
@Validated
@Tag(name = "国家信息管理")
@RestController
@RequestMapping(value = EmisConstants.V1_API_PATH + "/country")
public class CountryEndpoint {

    @Operation(summary = "获取国家信息列表")
    @GetMapping("/list")
    public ResponseResult<List<CountryUtils.CountryInfo>> list() {
        List<CountryUtils.CountryInfo> result = CountryUtils.COUNTRY.values().stream()
            .collect(Collectors.toList());
        return ResponseResult.ok(result);
    }
}
